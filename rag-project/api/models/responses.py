from pydantic import BaseModel, Field
from typing import Optional, List
import datetime


class SufficiencyInfo(BaseModel):
    sufficient: bool = Field(
        description="Whether retrieved context was judged sufficient to answer the query."
    )
    reason: str = Field(description="Short explanation of the sufficiency verdict.")
    tier: str = Field(
        description="Which gate produced the verdict: 'score_floor', 'llm_judge', or 'empty'."
    )


class QueryResponse(BaseModel):
    query_id : str = Field(
        description="Unique identifier for this request. Use for tracing and debugging."
    )

    query : str = Field(
        description="The original query as received."
    )

    rewritten_query: Optional[str] = Field(
        default=None,
        description="The query after LLM rewriting, as actually used for retrieval.",
    )

    answer : str = Field(
        description="The grounded answer generated by the LLM."
    )

    sources : List[str] = Field(
        description="Retrieved context chunks used to generate the answer."
    )

    chunks_used : int = Field(
        description="Number of chunks passed to the LLM."
    )

    provider : str = Field(
        description="The LLM provider that generated the answer."
    )

    latency_ms : float = Field(
        description="Total request latency in milliseconds."
    )

    timestamp : str = Field(
        description="UTC timestamt of the response."
    )


class IngestResponse(BaseModel):
    status : str = Field(
        description="'success' or 'already_exists'."
    )

    file_path : str

    chunks_created : Optional[int] = Field(
        default = None
    )

    message : str


class HealthResponse(BaseModel):
    status : str = Field(
        desription="'ok' or 'degraded'."
    )

    version : str
    pipeline_ready: bool
    timestamp: str
