from pydantic import BaseModel, Field
from typing import Optional, List
import datetime


class SufficiencyInfo(BaseModel):
    sufficient: bool = Field(
        description="Whether retrieved context was judged sufficient to answer the query."
    )

    reason: str = Field(description="Short explanation of the sufficiency verdict.")

    tier: str = Field(
        description="Which gate produced the verdict: 'score_floor', 'llm_judge', or 'empty'."
    )


class CitationVerificationInfo(BaseModel):
    grounded: bool = Field(
        description="Whether all claims in the answer are supported by cited sources."
    )

    unsupported_claims: List[str] = Field(
        default_factory=list,
        description="Claims not backed by cites sources. Empty if grounded, or if tier = 'no_citations' (not evaluated).",
    )

    reason: str = Field(description="Short explaination of the verification verdict.")

    tier: str = Field(
        description="Which gate produced the verdict: 'no_citation' or 'llm_judge'."
    )


class QueryResponse(BaseModel):
    query_id: str = Field(
        description="Unique identifier for this request. Use for tracing and debugging."
    )

    query: str = Field(description="The original query as received.")

    rewritten_query: Optional[str] = Field(
        default=None,
        description="The query after LLM rewriting, as actually used for retrieval.",
    )

    answer: str = Field(description="The grounded answer generated by the LLM.")

    sources: List[str] = Field(
        description="Retrieved context chunks used to generate the answer."
    )

    chunks_used: int = Field(description="Number of chunks passed to the LLM.")

    provider: str = Field(description="The LLM provider that generated the answer.")

    latency_ms: float = Field(description="Total request latency in milliseconds.")

    timestamp: str = Field(description="UTC timestamt of the response.")

    sufficiency: Optional[SufficiencyInfo] = Field(
        default=None,
        description="Context sufficiency gate result. None if the gate did not run.",
    )

    citation_check: Optional[CitationVerificationInfo] = Field(
        default=None,
        description="Citation Verification gate result. None if generation was skipped (e.g. abstain or insufficient context).",
    )

    confidence: Optional[str] = Field(
        default=None,
        description="'high' if citation verified, 'low' if not. None if generation was skipped.",
    )

    outcome: Optional[str] = Field(
        default=None,
        description="'abstain' | 'answer_low_confidence' | 'answer' — derived from sufficiency/citation_check/confidence.",
    )


class IngestResponse(BaseModel):
    status: str = Field(description="'success' or 'already_exists'.")

    file_path: str

    chunks_created: Optional[int] = Field(default=None)

    message: str


class HealthResponse(BaseModel):
    status: str = Field(desription="'ok' or 'degraded'.")

    version: str

    pipeline_ready: bool

    timestamp: str


class DeleteResponse(BaseModel):
    status: str = Field(description="'success'.")

    file_path: str

    chunks_deleted: int = Field(
        description="Number of chunks removed from the vector store."
    )

    message: str
